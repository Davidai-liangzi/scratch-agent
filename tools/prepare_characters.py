"""准备 Phase 6 种子角色：生成分层 SVG 与 manifest。

只在开发机手动运行，生成结果提交到 assets_characters/；
应用运行时不需要重新生成。

用法：
    python tools/prepare_characters.py
"""

import json
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from core import characters

OUT_DIR = os.path.join(ROOT, "assets_characters")
COUNT = 12
STYLE = "default"


def main():
    pack_dir = os.path.join(OUT_DIR, STYLE)
    shutil.rmtree(pack_dir, ignore_errors=True)
    os.makedirs(pack_dir, exist_ok=True)

    manifest = characters.build_manifest(COUNT, STYLE)
    for item in manifest["items"]:
        seed = int(item["seed"])
        svg = characters.compose_character(seed, STYLE)
        path = os.path.join(OUT_DIR, item["file"].replace("/", os.sep))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(svg)

    with open(os.path.join(OUT_DIR, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)

    with open(os.path.join(OUT_DIR, "LICENSE.txt"), "w", encoding="utf-8") as f:
        f.write(
            "Seed Characters\n"
            "Generated by core/characters.py (original geometric SVG art).\n"
            "No third-party LPC / DiceBear / Kenney art is included in this folder.\n"
        )
    print(f"完成：{len(manifest['items'])} 个种子角色 -> {OUT_DIR}")


if __name__ == "__main__":
    main()
